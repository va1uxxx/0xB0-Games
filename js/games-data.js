function tileInnerHTML(g) {
  if (g.thumb) {
    return (
      '<img src="' + g.thumb + '" alt="' + g.title + ' thumbnail" loading="lazy" ' +
      'onerror="this.style.display=\'none\';this.parentNode.style.background=\'linear-gradient(120deg,#131c33,#1d2a47)\'"/>'
    );
  }
  var c = CAT_COLORS[g.category] || ['#16223d', '#2a3f6b'];
  return (
    '<div class="emoji-tile" style="background:linear-gradient(140deg,' + c[0] + ',' + c[1] + ')">' +
    '<span class="emoji">' + (g.emoji || '🎮') + '</span>' +
    '<span class="tname">' + g.title + '</span>' +
    '</div>'
  );
}
